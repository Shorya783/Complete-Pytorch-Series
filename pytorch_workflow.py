import torch
from torch import nn # nn contains all of pytorch's building blocks for nn
import matplotlib.pyplot as plt

weight=0.7
bias=0.3
start=0
end=1
step=0.02
X=torch.arange(start,end,step).unsqueeze(dim=1)
y=weight*X+bias

train_split=int(0.8*len(X))
X_train,y_train=X[:train_split],X[:train_split]
X_test,y_test=X[train_split:],X[train_split:]

len(X_train),len(X_test),len(y_train),len(y_test)

y_test

def plot_predictions(train_data=X_train,train_labels=y_train,test_data=X_test,test_labels=y_test,predictions=None):
  plt.figure(figsize=(10,7))
  plt.scatter(train_data,train_labels,c="b",s=2,label="training data")
  plt.scatter(test_data,test_labels,c="g",s=2,label="testing data")
  if predictions is not None:
    plt.scatter(test_data,predictions,c="r",s=2,label="predictions")
  plt.legend()

plot_predictions()

class LinearRegressionModel(nn.Module): #almost everything in pytorch inherits from nn.Module
  def __init__(self):
    super().__init__()
    self.weights=nn.Parameter(torch.randn(1,requires_grad=True,dtype=torch.float))
    self.bias=nn.Parameter(torch.randn(1,requires_grad=True,dtype=torch.float))
  def forward(self,x:torch.tensor)->torch.tensor:
    return self.weights*x+self.bias

torch.manual_seed(42)
model_0=LinearRegressionModel()
list(model_0.parameters())

model_0.state_dict()

with torch.inference_mode():
  y_preds=model_0(X_test)
y_preds

plot_predictions(predictions=y_preds)

loss_fn=torch.nn.L1Loss()
optimizer=torch.optim.SGD(params=model_0.parameters(),lr=0.01)

model_0.state_dict()

epochs=500
epoch_count=[]
loss_values=[]
test_loss_values=[]
for epoch in range(epochs):
  model_0.train() # train mode in pytorch sets all parameters that require gradients
  y_pred=model_0(X_train)
  loss=loss_fn(y_pred,y_train)
  print(f"Loss {loss}")
  optimizer.zero_grad()
  loss.backward()
  optimizer.step()
  print(model_0.state_dict())
  model_0.eval() # turn off different settings of the model which are not required during testing/evaluation
  with torch.inference_mode(): # turns off gradient tracking
    test_pred=model_0(X_test)
    test_loss=loss_fn(test_pred,y_test)
    if(epoch%10==0):
      epoch_count.append(epoch)
      loss_values.append(loss)
      test_loss_values.append(test_loss)
      print(f"epochs :{epoch} | loss:{loss} | test_loss:{test_loss}")
      model_0.state_dict()

with torch.inference_mode():
  y_preds_new=model_0(X_test)
